/// Concrete MeshCore infrastructure environments from current variants,
/// upstream d929643 and the explicit qualified nRF52 target inventory.
/// Generated/custom filename combinations are never accepted as target IDs.
class NrfDfuTargetCatalog {
  static final _targets = _buildTargets();

  // Source-qualified Tower linker maps, not a family-wide flash-size guess.
  // variants/heltec_tower_v2/platformio.ini selects nrf52840_s140_v6.ld
  // or nrf52840_s140_v6_sd_ota.ld, both [0x26000, 0xED000).
  // The logical lean target is explicitly replaced by the same SD recipe
  // in build_legacy.sh:get_unified_meshtower_repeater_replacement.
  static const _towerLayouts = <String>{
    'Heltec_tower_v2_repeater',
    'Heltec_tower_v2_repeater_lora_ota_no_external_sensors',
    'Heltec_tower_v2_sdcard_repeater_lora_ota_no_external_sensors',
    'Heltec_tower_v2_room_server',
  };

  static Map<int, (String, String)> _buildTargets() {
    final result = <int, (String, String)>{};
    for (final environment in environments) {
      final match = RegExp(
        r'_(repeater|repeat|repeatr|room_server|room_svr)(?:_|-|$)',
        caseSensitive: false,
      ).firstMatch(environment)!;
      final id = ByteData.sublistView(
        Uint8List.fromList(
          crypto.sha256.convert(utf8.encode(environment)).bytes,
        ),
      ).getUint32(0, Endian.little);
      if (result.containsKey(id)) {
        throw StateError('Reviewed infrastructure target IDs collide.');
      }
      final role = match.group(1)!.toLowerCase().startsWith('room')
          ? 'roomServer'
          : 'repeater';
      result[id] = (
        _towerLayouts.contains(environment)
            ? 'Heltec_tower_v2'
            : environment.substring(0, match.start),
        role,
      );
    }
    return Map.unmodifiable(result);
  }

  static bool supports(
    int targetId,
    CompanionBoardSpec board,
    String role, {
    int? expectedTargetId,
  }) {
    if (targetId == 0) return false;
    final entry = _targets[targetId];
    if (entry == null || entry.$2 != role) return false;
    if (board.assetPrefixes.any(
      (prefix) => prefix.toLowerCase() == entry.$1.toLowerCase(),
    )) {
      return true;
    }
    // Qualified logical targets may hash a storage alias while their actual
    // PIO image retains a different physical hardware tag. A positive ID
    // independently read over authenticated CLI is required in that case.
    return expectedTargetId != null &&
        expectedTargetId > 0 &&
        expectedTargetId == targetId;
  }

  /// Additional capacity is admitted only by an exact reviewed role target.
  /// All other targets retain the board's conservative Companion limit.
  static int? applicationMaximum(
    int targetId,
    CompanionBoardSpec board,
    String role, {
    int? expectedTargetId,
  }) {
    if (board.id != 'heltec-tower-v2' ||
        board.nrfApplicationAddress != 0x26000 ||
        !supports(targetId, board, role, expectedTargetId: expectedTargetId)) {
      return null;
    }
    for (final environment in _towerLayouts) {
      final bytes = Uint8List.fromList(
        crypto.sha256.convert(utf8.encode(environment)).bytes,
      );
      if (ByteData.sublistView(bytes).getUint32(0, Endian.little) == targetId) {
        return 0xc7000;
      }
    }
    return null;
  }

