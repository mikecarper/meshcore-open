/// Exact board identities from MeshCore variants and OTAFIX board definitions.
/// Unknown names are not guessed from vendor or MCU substrings. Firmware can
/// disable an otherwise available transport, so capability probes still apply.
enum CompanionChipFamily { nrf52, esp32, rp2040 }

class CompanionBoardSpec {
  const CompanionBoardSpec({
    required this.id,
    required this.family,
    required this.aliases,
    required this.assetPrefixes,
    required this.hardwareIds,
    this.dfuNames = const [],
    this.espChipId,
    this.supportsWifiOta = false,
    this.nrfApplicationAddress,
    this.nrfApplicationMaxSize,
    this.nrfSoftdeviceIds = const [],
  });

  final String id;
  final CompanionChipFamily family;
  final List<String> aliases;
  final List<String> assetPrefixes;
  final List<String> hardwareIds;

  /// Exact bootloader names, including their known eight-byte advertisements.
  /// These never include an application's BLE OTA-mode name as a guess.
  final List<String> dfuNames;
  final int? espChipId;

  /// False for known wired-only C6 Companion firmware. True means supported
  /// by the known firmware family, not proof of the installed build's capability.
  final bool supportsWifiOta;

  /// Verified Companion linker region and installed SoftDevice requirements.
  /// Null geometry is deliberately unsupported, rather than a guessed layout.
  final int? nrfApplicationAddress;
  final int? nrfApplicationMaxSize;
  final List<int> nrfSoftdeviceIds;

  String? get updateExtension => switch (family) {
    CompanionChipFamily.nrf52 => 'zip',
    CompanionChipFamily.esp32 => 'bin',
    CompanionChipFamily.rp2040 => null,
  };

  bool get supportsWirelessUpdate =>
      family == CompanionChipFamily.nrf52 ||
      family == CompanionChipFamily.esp32 && supportsWifiOta;
}

